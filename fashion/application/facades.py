from uuid import UUID

from fashion.application.dto import *  # noqa: F401,F403
from fashion.application.ports_in import (
    BrandUseCase, CollectionUseCase, DesignerUseCase, GenerationUseCase,
    RecommendationUseCase, SearchUseCase,
)
from fashion.application.services import (
    BrandInformationService, BrandRecommendationService, CollaborationService,
    CollectionInformationService, DataGenerationService, DesignerInformationService,
    FullTextSearchService, GarmentInformationService, SearchCacheService,
)


class DesignerFacade(DesignerUseCase):
    def __init__(self, information: DesignerInformationService,
                 collaboration: CollaborationService): ...
    def create_designer(self, dto: DesignerCreateDto) -> DesignerDto: ...
    def get_designer(self, designer_id: UUID) -> DesignerDetailsDto: ...
    def list_designers(self, page: int, size: int) -> list[DesignerDto]: ...
    def update_designer(self, designer_id: UUID, dto: DesignerCreateDto) -> DesignerDto: ...
    def delete_designer(self, designer_id: UUID) -> None: ...


class BrandFacade(BrandUseCase):
    def __init__(self, information: BrandInformationService,
                 collaboration: CollaborationService): ...
    def create_brand(self, dto: BrandCreateDto) -> BrandDto: ...
    def get_brand(self, brand_id: UUID) -> BrandDetailsDto: ...   
    def list_brands(self, page: int, size: int) -> list[BrandDto]: ...
    def update_brand(self, brand_id: UUID, dto: BrandCreateDto) -> BrandDto: ...
    def delete_brand(self, brand_id: UUID) -> None: ...


class CollectionFacade(CollectionUseCase):
    def __init__(self, information: CollectionInformationService,
                 garments: GarmentInformationService,
                 brands: BrandInformationService,
                 designers: DesignerInformationService): ...
    def create_collection(self, dto: CollectionCreateDto) -> CollectionDto: ...
    def get_collection(self, collection_id: UUID) -> CollectionDetailsDto: ...
    def filter_collections(self, f: CollectionFilterDto) -> list[CollectionDto]: ...
    def update_collection(self, collection_id: UUID, dto: CollectionCreateDto) -> CollectionDto: ...
    def delete_collection(self, collection_id: UUID) -> None: ...
    def add_garment(self, dto: GarmentCreateDto) -> GarmentDto: ...
    def delete_garment(self, garment_id: UUID) -> None: ...


class SearchFacade(SearchUseCase):
    def __init__(self, search: FullTextSearchService, cache: SearchCacheService): ...
    def search(self, request: SearchRequestDto) -> SearchResultDto: ...


class RecommendationFacade(RecommendationUseCase):
    def __init__(self, recommendation: BrandRecommendationService,
                 collections: CollectionInformationService): ...
    def recommend_for_brand(self, brand_id: UUID) -> RecommendationDto: ...
    def recommend_for_collection(self, collection_id: UUID) -> RecommendationDto: ...


class GenerationFacade(GenerationUseCase):
    def __init__(self, generation: DataGenerationService): ...
    def save_designer(self, dto: DesignerCreateDto) -> DesignerDto: ...
    def save_brand(self, dto: BrandCreateDto) -> BrandDto: ...
    def save_collection(self, dto: CollectionCreateDto) -> CollectionDto: ...
    def save_garment(self, dto: GarmentCreateDto) -> GarmentDto: ...
