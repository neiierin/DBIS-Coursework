# Вхідні адаптери
from uuid import UUID

from fashion.application.dto import *  # noqa: F401,F403
from fashion.application.ports_in import (
    BrandUseCase, CollectionUseCase, DesignerUseCase, GenerationUseCase,
    RecommendationUseCase, SearchUseCase,
)


#REST-контролери
class BrandController:
    def __init__(self, facade: BrandUseCase): ...
    def create(self, dto: BrandCreateDto) -> BrandDto: ...                  # POST   /api/brands
    def get(self, brand_id: UUID) -> BrandDetailsDto: ...                   # GET    /api/brands/{id}
    def list(self, page: int = 0, size: int = 20) -> list[BrandDto]: ...    # GET    /api/brands
    def update(self, brand_id: UUID, dto: BrandCreateDto) -> BrandDto: ...  # PUT    /api/brands/{id}
    def delete(self, brand_id: UUID) -> None: ...                           # DELETE /api/brands/{id}


class DesignerController:
    def __init__(self, facade: DesignerUseCase): ...
    def create(self, dto: DesignerCreateDto) -> DesignerDto: ...
    def get(self, designer_id: UUID) -> DesignerDetailsDto: ...
    def list(self, page: int = 0, size: int = 20) -> list[DesignerDto]: ...
    def update(self, designer_id: UUID, dto: DesignerCreateDto) -> DesignerDto: ...
    def delete(self, designer_id: UUID) -> None: ...


class CollectionController:
    def __init__(self, facade: CollectionUseCase): ...
    def create(self, dto: CollectionCreateDto) -> CollectionDto: ...
    def get(self, collection_id: UUID) -> CollectionDetailsDto: ...
    def filter(self, season: str | None = None, year: int | None = None,
               style: str | None = None, page: int = 0, size: int = 20) -> list[CollectionDto]: ...
    def update(self, collection_id: UUID, dto: CollectionCreateDto) -> CollectionDto: ...
    def delete(self, collection_id: UUID) -> None: ...
    def add_garment(self, collection_id: UUID, dto: GarmentCreateDto) -> GarmentDto: ...
    def delete_garment(self, collection_id: UUID, garment_id: UUID) -> None: ...


class SearchController:
    def __init__(self, facade: SearchUseCase): ...
    def search(self, q: str, page: int = 0, size: int = 20) -> SearchResultDto: ...   # GET /api/search?q=


class RecommendationController:
    def __init__(self, facade: RecommendationUseCase): ...
    def for_brand(self, brand_id: UUID) -> RecommendationDto: ...         # GET /api/recommendations/brand/{id}
    def for_collection(self, collection_id: UUID) -> RecommendationDto: ...


#Генератор даних
class DataGenerator:
    def __init__(self, facade: GenerationUseCase, rate_per_second: float = 5.0): ...
    def run(self) -> None: ...
    def generate_designer(self) -> None: ...
    def generate_brand(self) -> None: ...
    def generate_collection(self) -> None: ...
    def generate_garment(self) -> None: ...
