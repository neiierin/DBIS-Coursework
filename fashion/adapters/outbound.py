# Вихідні адаптери
from uuid import UUID

from fashion.application.dto import (
    CollaborationDto, CollectionFilterDto, SearchRequestDto, SearchResultDto,
)
from fashion.application.ports_out import (
    BrandRepository, CacheRepository, CollectionRepository, DesignerRepository,
    GarmentRepository, RecommendationGraphRepository, RelationGraphRepository,
    SearchIndexRepository,
)
from fashion.domain.models import Brand, Collection, Designer, Garment


#MongoDB
class MongoDesignerRepository(DesignerRepository):
    def __init__(self, db): ...
    def create(self, entity: Designer) -> Designer: ...
    def get_by_id(self, id: UUID) -> Designer | None: ...
    def get_all(self, page: int = 0, size: int = 20) -> list[Designer]: ...
    def update(self, id: UUID, entity: Designer) -> Designer: ...
    def delete(self, id: UUID) -> None: ...


class MongoBrandRepository(BrandRepository):
    def __init__(self, db): ...
    def create(self, entity: Brand) -> Brand: ...
    def get_by_id(self, id: UUID) -> Brand | None: ...
    def get_all(self, page: int = 0, size: int = 20) -> list[Brand]: ...
    def update(self, id: UUID, entity: Brand) -> Brand: ...
    def delete(self, id: UUID) -> None: ...
    def find_by_style_category(self, style_category: str) -> list[Brand]: ...


class MongoCollectionRepository(CollectionRepository):
    def __init__(self, db): ...
    def create(self, entity: Collection) -> Collection: ...
    def get_by_id(self, id: UUID) -> Collection | None: ...
    def get_all(self, page: int = 0, size: int = 20) -> list[Collection]: ...
    def update(self, id: UUID, entity: Collection) -> Collection: ...
    def delete(self, id: UUID) -> None: ...
    def find_by_filter(self, f: CollectionFilterDto) -> list[Collection]: ...
    def find_by_brand_id(self, brand_id: UUID) -> list[Collection]: ...


class MongoGarmentRepository(GarmentRepository):
    def __init__(self, db): ...
    def create(self, entity: Garment) -> Garment: ...
    def get_by_id(self, id: UUID) -> Garment | None: ...
    def get_all(self, page: int = 0, size: int = 20) -> list[Garment]: ...
    def update(self, id: UUID, entity: Garment) -> Garment: ...
    def delete(self, id: UUID) -> None: ...
    def find_by_collection_id(self, collection_id: UUID) -> list[Garment]: ...


#Neo4j
class Neo4jRelationRepository(RelationGraphRepository):
    def __init__(self, driver): ...
    def link_designer_to_collection(self, designer_id: UUID, collection_id: UUID) -> None: ...  # :РОЗРОБИВ
    def link_collection_to_brand(self, collection_id: UUID, brand_id: UUID) -> None: ...        # :ПРЕДСТАВЛЕНА_БРЕНДОМ
    def find_collaborations(self, designer_id: UUID) -> list[CollaborationDto]: ...
    def delete_node(self, entity_id: UUID) -> None: ...


class Neo4jRecommendationRepository(RecommendationGraphRepository):
    def __init__(self, driver): ...
    def find_similar_brand_ids(self, brand_id: UUID, limit: int = 5) -> list[UUID]: ...


#Elasticsearch
class ElasticsearchSearchRepository(SearchIndexRepository):
    def __init__(self, client): ...
    def search(self, request: SearchRequestDto) -> SearchResultDto: ...
    def index_collection(self, collection: Collection) -> None: ...
    def index_designer(self, designer: Designer) -> None: ...
    def delete_from_index(self, entity_type: str, entity_id: UUID) -> None: ...


#Redis
class RedisCacheRepository(CacheRepository):
    def __init__(self, client): ...
    def get(self, key: str) -> object | None: ...
    def put(self, key: str, value: object, ttl_seconds: int = 300) -> None: ...
    def invalidate(self, prefix: str) -> None: ...
